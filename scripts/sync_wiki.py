"""Publish ``docs/*.md`` into a checkout of the repository's GitHub wiki.

The wiki is a separate git repository (``<repo>.wiki.git``). The workflow
``.github/workflows/wiki.yml`` clones it, runs this script and pushes the
result. The script is stdlib-only so it can run without installing the
project or its dependencies.

Rules:

* every ``docs/*.md`` becomes a wiki page with the same file name;
* relative links between docs become wiki links (``auth.md`` -> ``auth``);
* links to other repository files become absolute GitHub blob URLs;
* ``Home.md`` and ``_Sidebar.md`` are generated as an index and navigation;
* generated pages carry a marker; pages removed from ``docs/`` are deleted
  from the wiki, while manually created wiki pages are left alone.
"""

from __future__ import annotations

import argparse
import posixpath
import re
import sys
from dataclasses import dataclass
from pathlib import Path

MARKER_PREFIX = "<!-- generated by scripts/sync_wiki.py"
RESERVED_PAGES = {"home.md", "_sidebar.md", "_footer.md"}
LINK_RE = re.compile(r"\]\(([^)\s]+)\)")


@dataclass(frozen=True)
class SyncResult:
    written: tuple[str, ...]
    removed: tuple[str, ...]


def _marker(source: str) -> str:
    return f"{MARKER_PREFIX} from docs/{source}; edit the source instead -->"


def _read_markdown(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    return text.replace("\r\n", "\n").replace("\r", "\n")


def _write_markdown(path: Path, text: str) -> None:
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")


def _page_title(text: str, fallback: str) -> str:
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            return stripped[2:].strip() or fallback
    return fallback


def _rewrite_link(
    destination: str,
    *,
    pages: dict[str, str],
    repo_url: str,
    branch: str,
) -> str:
    if destination.startswith(("http://", "https://", "mailto:", "#")):
        return destination

    path, separator, fragment = destination.partition("#")
    if not path:
        return destination

    name = posixpath.basename(path)
    if name in pages:
        suffix = f"#{fragment}" if separator else ""
        return pages[name] + suffix

    resolved = posixpath.normpath(posixpath.join("docs", path))
    if resolved == ".." or resolved.startswith("../"):
        return destination

    suffix = f"#{fragment}" if separator else ""
    return f"{repo_url}/blob/{branch}/{resolved}{suffix}"


def _rewrite_links(
    text: str,
    *,
    pages: dict[str, str],
    repo_url: str,
    branch: str,
) -> str:
    def replace(match: re.Match[str]) -> str:
        destination = match.group(1)
        rewritten = _rewrite_link(destination, pages=pages, repo_url=repo_url, branch=branch)
        return f"]({rewritten})"

    return LINK_RE.sub(replace, text)


def _render_home(titles: dict[str, str], *, repo_url: str, branch: str) -> str:
    lines = [
        f"{MARKER_PREFIX}; edit docs/*.md instead -->",
        "",
        "# FreeProxyAPI — документация",
        "",
        f"Источник страниц — [`docs/`]({repo_url}/tree/{branch}/docs). "
        f"Wiki обновляется автоматически при пуше в `{branch}`.",
        "",
        "| Раздел | Исходник |",
        "|---|---|",
    ]
    for source in sorted(titles):
        title = titles[source].replace("|", "\\|")
        page = source.removesuffix(".md")
        lines.append(
            f"| [{title}]({page}) | [docs/{source}]({repo_url}/blob/{branch}/docs/{source}) |"
        )
    return "\n".join(lines)


def _render_sidebar(titles: dict[str, str]) -> str:
    lines = [
        f"{MARKER_PREFIX}; edit docs/*.md instead -->",
        "",
        "**[FreeProxyAPI](Home)**",
        "",
    ]
    for source in sorted(titles):
        page = source.removesuffix(".md")
        lines.append(f"- [{titles[source]}]({page})")
    return "\n".join(lines)


def _remove_stale_pages(destination: Path, keep: set[str]) -> list[str]:
    removed: list[str] = []
    for path in sorted(destination.glob("*.md")):
        if path.name in keep or path.name.lower() in RESERVED_PAGES:
            continue
        try:
            head = path.read_text(encoding="utf-8", errors="ignore")[:128]
        except OSError:
            continue
        if head.startswith(MARKER_PREFIX):
            path.unlink()
            removed.append(path.name)
    return removed


def sync(
    source: Path,
    destination: Path,
    *,
    repo_url: str,
    branch: str = "master",
) -> SyncResult:
    source = Path(source)
    destination = Path(destination)
    if not source.is_dir():
        raise FileNotFoundError(f"docs directory not found: {source}")
    destination.mkdir(parents=True, exist_ok=True)
    repo_url = repo_url.rstrip("/")

    documents: dict[str, str] = {}
    for path in sorted(source.glob("*.md")):
        if path.name.lower() in RESERVED_PAGES:
            raise ValueError(f"docs page name is reserved by the wiki: {path.name}")
        documents[path.name] = _read_markdown(path)

    pages = {name: name.removesuffix(".md") for name in documents}
    titles = {name: _page_title(text, name.removesuffix(".md")) for name, text in documents.items()}

    written: list[str] = []
    for name, text in documents.items():
        body = _rewrite_links(text, pages=pages, repo_url=repo_url, branch=branch)
        _write_markdown(destination / name, f"{_marker(name)}\n\n{body}")
        written.append(name)

    _write_markdown(
        destination / "Home.md",
        _render_home(titles, repo_url=repo_url, branch=branch),
    )
    _write_markdown(destination / "_Sidebar.md", _render_sidebar(titles))
    written.extend(("Home.md", "_Sidebar.md"))

    removed = _remove_stale_pages(destination, set(documents))
    return SyncResult(written=tuple(written), removed=tuple(removed))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("docs"))
    parser.add_argument("--dest", type=Path, required=True)
    parser.add_argument("--repo-url", required=True)
    parser.add_argument("--branch", default="master")
    args = parser.parse_args(argv)

    result = sync(
        args.source,
        args.dest,
        repo_url=args.repo_url,
        branch=args.branch,
    )
    print(f"wiki: wrote {len(result.written)} page(s), removed {len(result.removed)} stale page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
