from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any

from .paths import AuthPaths
from .store import TokenStore, secure_write


def _export_dir(paths: AuthPaths, provider: str) -> Path:
    return paths.export_dir / provider


def _repo_or_export(paths: AuthPaths, provider: str, repo: Path) -> Path:
    return repo if repo.is_dir() else _export_dir(paths, provider)


def _write_json(path: Path, payload: Any) -> None:
    secure_write(
        path,
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
    )


def export_deepseek(data: dict[str, Any], paths: AuthPaths) -> Path:
    target = _repo_or_export(paths, "deepseek", paths.deepseek_repo) / "deepseek-auth.json"
    cookies = data.get("cookies") or []
    cookie = str(data.get("cookie") or "")
    if not cookie and isinstance(cookies, list):
        cookie = "; ".join(
            f"{item.get('name')}={item.get('value')}"
            for item in cookies
            if isinstance(item, dict) and item.get("name") and item.get("value")
        )
    payload = {
        "token": str(data.get("token") or ""),
        "hif_dliq": str(data.get("hif_dliq") or ""),
        "hif_leim": str(data.get("hif_leim") or ""),
        "cookie": cookie,
        "wasmUrl": str(
            data.get("wasm_url")
            or "https://fe-static.deepseek.com/chat/static/sha3_wasm_bg.7b9ca65ddd.wasm"
        ),
    }
    _write_json(target, payload)
    return target


def export_qwen(data: dict[str, Any], paths: AuthPaths) -> list[Path]:
    base = _repo_or_export(paths, "qwen", paths.qwen_repo)
    session = base / "session"
    token = str(data.get("token") or "")
    cookies = data.get("cookies") or []
    baxia_headers = data.get("baxia_headers") or {}

    tokens_path = session / "tokens.json"
    existing: list[dict[str, Any]] = []
    if tokens_path.is_file():
        try:
            loaded = json.loads(tokens_path.read_text(encoding="utf-8"))
            if isinstance(loaded, list):
                existing = [item for item in loaded if isinstance(item, dict)]
        except (OSError, json.JSONDecodeError):
            existing = []

    account = next((item for item in existing if item.get("token") == token), None)
    if account is None:
        used = {str(item.get("id")) for item in existing}
        base_ms = int(time.time() * 1000)
        suffix = 0
        account_id = f"acc_{base_ms}"
        while account_id in used:
            suffix += 1
            account_id = f"acc_{base_ms + suffix}"
        account = {
            "id": account_id,
            "token": token,
            "resetAt": None,
            "label": "freeproxy-auth",
        }
        existing.append(account)
    account_id = str(account.get("id"))
    account_dir = session / "accounts" / account_id
    account_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    token_path = session / "auth_token.txt"
    secure_write(token_path, token)
    written.append(token_path)

    _write_json(tokens_path, existing)
    written.append(tokens_path)

    account_token = account_dir / "token.txt"
    secure_write(account_token, token)
    written.append(account_token)

    if isinstance(cookies, list) and cookies:
        cookies_path = account_dir / "cookies.json"
        _write_json(cookies_path, cookies)
        written.append(cookies_path)

    if isinstance(baxia_headers, dict) and baxia_headers:
        baxia_path = session / "baxia.json"
        _write_json(baxia_path, {"headers": baxia_headers})
        written.append(baxia_path)

    return written


def write_upstream_env(data: dict[str, Any], paths: AuthPaths) -> Path | None:
    token = str(data.get("token") or "")
    if not token or "\n" in token or "\r" in token:
        return None
    path = paths.upstream_env_path
    secure_write(path, f"# Generated by freeproxy-auth\nZAI_TOKEN={token}\n")
    return path


def export_provider(store: TokenStore, paths: AuthPaths, provider: str) -> list[Path]:
    data = store.provider(provider)
    if not data or not data.get("token"):
        return []
    expires_at = data.get("expires_at")
    if isinstance(expires_at, (int, float)) and int(expires_at) <= int(time.time()):
        return []
    if provider == "deepseek":
        return [export_deepseek(data, paths)]
    if provider == "qwen":
        return export_qwen(data, paths)
    if provider == "glm":
        path = write_upstream_env(data, paths)
        return [path] if path else []
    return []


def export_all(store: TokenStore, paths: AuthPaths) -> dict[str, list[str]]:
    result: dict[str, list[str]] = {}
    for provider in ("deepseek", "qwen", "glm"):
        files = export_provider(store, paths, provider)
        if files:
            result[provider] = [str(path) for path in files]
    return result
